package com.example.legmasky.model;

public class SunInfo {
    public String dawn;      // alba civile (inizio luce), ISO 8601
    public String sunrise;   // sorgere del sole, ISO 8601
    public String noon;      // mezzogiorno solare, ISO 8601
    public String sunset;    // tramonto, ISO 8601
    public String dusk;      // crepuscolo civile (fine luce), ISO 8601
    public int day_length_minutes;
}